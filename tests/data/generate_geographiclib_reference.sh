# Generates geographiclib_reference.inc: WGS84 reference values for the geodesy tests,
# computed with GeographicLib's CartConvert. On Debian and Ubuntu, CartConvert is in the
# geographiclib-tools package.
#
# Usage: tests/data/generate_geographiclib_reference.sh > tests/data/geographiclib_reference.inc

set -euo pipefail

command -v CartConvert >/dev/null || { echo "CartConvert not found; install geographiclib-tools" >&2; exit 1; }

precision=10
version=$(CartConvert --version 2>&1 | sed -n 's/.*GeographicLib version \([0-9.]*\).*/\1/p')

latitudes="-90 -89.9999 -60 -45.5 -0.000001 0 30 52.1 89.9 90"
longitudes="-180 -123.4 0 45 179.999"
heights="-10000 0 8848.86 100000 35786000"

cat <<HEADER
// SPDX-License-Identifier: MIT
// Copyright (c) 2026 Jeremiah van Oosten
//
// WGS84 reference values from GeographicLib ${version} (CartConvert -p ${precision}).
// Generated by tests/data/generate_geographiclib_reference.sh; do not edit.
// clang-format off

HEADER

# Geodetic to geocentric: {latitude, longitude, height, x, y, z}, angles in degrees.
echo "inline constexpr double geocentric_forward[][6] = {"
for lat in $latitudes; do
    for lon in $longitudes; do
        for h in $heights; do
            read -r x y z < <(echo "$lat $lon $h" | CartConvert -p $precision)
            echo "    {$lat, $lon, $h, $x, $y, $z},"
        done
    done
done
echo "};"
echo

# Geocentric to geodetic for points near the centre of the ellipsoid, inside and around the
# evolute, and on the polar axis: {x, y, z, latitude, longitude, height}.
echo "inline constexpr double geocentric_reverse[][6] = {"
while read -r x y z; do
    read -r lat lon h < <(echo "$x $y $z" | CartConvert -r -p $precision)
    echo "    {$x, $y, $z, $lat, $lon, $h},"
done <<POINTS
0 0 1
0 0 -6356752
0 0 7000000
1 0 0
1000 2000 0
30000 0 0
42000 1000 0
42700 0 1
20000 -10000 500
40000 0 -20000
100000 100000 100000
-3000000 -2000000 4000000
6378137 0 0
6378136 0 1e-6
0 0 6356752.314245
1e9 2e9 -3e9
POINTS
echo "};"
echo

# Geodetic to local East-North-Up: {origin latitude, origin longitude, origin height,
# latitude, longitude, height, east, north, up}.
echo "inline constexpr double local_enu[][9] = {"
while read -r lat0 lon0 h0; do
    while read -r lat lon h; do
        read -r e n u < <(echo "$lat $lon $h" | CartConvert -l "$lat0" "$lon0" "$h0" -p $precision)
        echo "    {$lat0, $lon0, $h0, $lat, $lon, $h, $e, $n, $u},"
    done <<TARGETS
52.2 5.2 100
52.1 5.1 10
-33.9 151.2 0
0 0 0
89.9 45 1000
-45 -120 -5000
10 179.5 2000000
TARGETS
done <<ORIGINS
52.1 5.1 10
-33.9 151.2 0
0 180 0
89.99 0 0
-90 0 0
ORIGINS
echo "};"
